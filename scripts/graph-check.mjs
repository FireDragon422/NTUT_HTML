import fs from 'node:fs';import path from 'node:path';import {spawnSync} from 'node:child_process';
const root=process.cwd(),fixture=path.join(root,'tmp/graph-test-'+Date.now());
fs.mkdirSync(path.join(fixture,'scripts'),{recursive:true});
fs.copyFileSync('scripts/graph-control.mjs',path.join(fixture,'scripts/graph-control.mjs'));
for(const dir of ['workflow/runs/v2-outline','wiki','sources','slides'])fs.cpSync(dir,path.join(fixture,dir),{recursive:true});
const statePath=path.join(fixture,'workflow/runs/v2-outline/state.json');
const state=JSON.parse(fs.readFileSync(statePath));
const tests=[];
const attempt=(args,expected,label)=>{const r=spawnSync(process.execPath,['scripts/graph-control.mjs',...args],{cwd:fixture,encoding:'utf8'});const passed=r.status===expected;tests.push({label,passed,observed:r.stderr.trim()||r.stdout.trim()});if(!passed)process.exitCode=1;};
attempt(['render'],1,'未審查不得排版');
attempt(['complete'],1,'未呈現檢查不得交付');
attempt(['approve','重複確認'],1,'不得重複確認以重設狀態');
fs.appendFileSync(path.join(fixture,'workflow/runs/v2-outline/outline.json'),' ');
attempt(['freeze'],1,'大綱變動會阻擋下游');
fs.copyFileSync('workflow/runs/v2-outline/outline.json',path.join(fixture,'workflow/runs/v2-outline/outline.json'));
fs.appendFileSync(path.join(fixture,'wiki/W03.md'),'\nchanged');
attempt(['freeze'],1,'來源變動會阻擋下游');
fs.copyFileSync('wiki/W03.md',path.join(fixture,'wiki/W03.md'));
state.status='revision_required';state.revisions=2;fs.writeFileSync(statePath,JSON.stringify(state));
attempt(['freeze'],1,'第三次內容修訂停止');
fs.writeFileSync('tmp/graph-check.json',JSON.stringify({tests,passed:tests.every(t=>t.passed)},null,2));
console.log(JSON.stringify(tests,null,2));
